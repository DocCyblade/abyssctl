// Command gendocs generates the command reference in docs/reference from abyssctl's help text.
//
//	gendocs -out docs/reference    writes one page per command and deletes stale pages (make docs)
//	gendocs -check docs/reference  compares the pages in memory and writes nothing (make docs-check)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"

	"github.com/DocCyblade/abyssctl/internal/cli"
)

// header is the first line of every page.
const header = "<!-- Generated by make docs from abyssctl's help text. Do not edit: run make docs. -->\n"

func main() { os.Exit(run(os.Args[1:], os.Stderr)) }

// run is the whole command; it returns the exit code.
func run(args []string, stderr io.Writer) int {
	fs := flag.NewFlagSet("gendocs", flag.ContinueOnError)
	fs.SetOutput(stderr)
	out := fs.String("out", "", "write the pages into this folder and delete stale ones")
	check := fs.String("check", "", "compare the pages with this folder and write nothing")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if (*out == "") == (*check == "") || fs.NArg() != 0 {
		_, _ = fmt.Fprintln(stderr, "usage: gendocs -out <folder> | -check <folder>")
		return 2
	}

	pages, err := generate(cli.Root())
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "gendocs: %v\n", err)
		return 1
	}
	if *out != "" {
		if err := write(*out, pages); err != nil {
			_, _ = fmt.Fprintf(stderr, "gendocs: %v\n", err)
			return 1
		}
		return 0
	}
	diffs, err := compare(*check, pages)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "gendocs: %v\n", err)
		return 1
	}
	if len(diffs) == 0 {
		return 0
	}
	for _, d := range diffs {
		_, _ = fmt.Fprintln(stderr, d)
	}
	_, _ = fmt.Fprintln(stderr, "docs/reference is out of date: run make docs")
	return 1
}

// page is one generated reference page.
type page struct {
	name string
	body []byte
}

// generate walks the tree depth first, children in Cobra's sorted order, and renders one page per available
// command.
func generate(root *cobra.Command) ([]page, error) {
	disableAutoGenTag(root)
	var pages []page
	var walk func(c *cobra.Command) error
	walk = func(c *cobra.Command) error {
		if !c.IsAvailableCommand() || c.IsAdditionalHelpTopicCommand() {
			return nil
		}
		var buf bytes.Buffer
		buf.WriteString(header)
		if err := doc.GenMarkdownCustom(c, &buf, linkHandler); err != nil {
			return fmt.Errorf("%s: %w", c.CommandPath(), err)
		}
		pages = append(pages, page{name: pageName(c), body: buf.Bytes()})
		for _, sub := range c.Commands() {
			if err := walk(sub); err != nil {
				return err
			}
		}
		return nil
	}
	return pages, walk(root)
}

func disableAutoGenTag(c *cobra.Command) {
	c.DisableAutoGenTag = true
	for _, sub := range c.Commands() {
		disableAutoGenTag(sub)
	}
}

func pageName(c *cobra.Command) string { return strings.ReplaceAll(c.CommandPath(), " ", "_") + ".md" }

// linkHandler links a page by its bare file name, since every page is in the same folder.
func linkHandler(name string) string { return name }

// isPage reports whether a file name is one the generator owns.
func isPage(name string) bool {
	return strings.HasPrefix(name, "abyssctl") && strings.HasSuffix(name, ".md")
}

// write writes every page into dir and deletes any other abyssctl*.md there.
func write(dir string, pages []page) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	written := map[string]bool{}
	for _, p := range pages {
		if err := os.WriteFile(filepath.Join(dir, p.name), p.body, 0o644); err != nil {
			return err
		}
		written[p.name] = true
	}
	existing, err := existingPages(dir)
	if err != nil {
		return err
	}
	for _, name := range existing {
		if !written[name] {
			if err := os.Remove(filepath.Join(dir, name)); err != nil {
				return err
			}
		}
	}
	return nil
}

// compare returns one `stale`, `missing` or `extra` line per page that differs from dir, in page-name order.
func compare(dir string, pages []page) ([]string, error) {
	existing, err := existingPages(dir)
	if err != nil {
		return nil, err
	}
	onDisk := map[string]bool{}
	for _, name := range existing {
		onDisk[name] = true
	}
	lines := map[string]string{}
	for _, p := range pages {
		if !onDisk[p.name] {
			lines[p.name] = "missing " + p.name
			continue
		}
		delete(onDisk, p.name)
		b, err := os.ReadFile(filepath.Join(dir, p.name))
		if err != nil {
			return nil, err
		}
		if !bytes.Equal(b, p.body) {
			lines[p.name] = "stale " + p.name
		}
	}
	for name := range onDisk {
		lines[name] = "extra " + name
	}
	names := make([]string, 0, len(lines))
	for name := range lines {
		names = append(names, name)
	}
	slices.Sort(names)
	out := make([]string, len(names))
	for i, name := range names {
		out[i] = lines[name]
	}
	return out, nil
}

// existingPages lists the abyssctl*.md files in dir; a missing folder has none.
func existingPages(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && isPage(e.Name()) {
			names = append(names, e.Name())
		}
	}
	return names, nil
}
