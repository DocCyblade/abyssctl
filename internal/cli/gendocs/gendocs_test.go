// runMainEnv, when set, makes the test binary act as gendocs itself, so the tests run it as `make docs` does:
// as its own process, with its own arguments and environment.
const runMainEnv = "GENDOCS_TEST_RUN_MAIN"

func TestMain(m *testing.M) {
	if os.Getenv(runMainEnv) == "1" {
		main()
		os.Exit(0)
	}
	os.Exit(m.Run())
}

// gendocs runs the generator with args and the extra environment variables, and returns its stderr and exit code.
func gendocs(t *testing.T, env []string, args ...string) (stderr string, code int) {
	t.Helper()
	cmd := exec.Command(os.Args[0], args...)
	cmd.Env = append(append(os.Environ(), runMainEnv+"=1"), env...)
	var errBuf strings.Builder
	cmd.Stderr = &errBuf
	err := cmd.Run()
	var exit *exec.ExitError
	switch {
	case err == nil:
		return errBuf.String(), 0
	case errors.As(err, &exit):
		return errBuf.String(), exit.ExitCode()
	default:
		t.Fatalf("running gendocs: %v", err)
		return "", 0
	}
}

// runOut runs `gendocs -out` into a new folder and returns it.
func runOut(t *testing.T, env ...string) string {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "reference")
	if stderr, code := gendocs(t, env, "-out", dir); code != 0 {
		t.Fatalf("gendocs -out: exit %d\n%s", code, stderr)
	}
	return dir
}

// pages reads every file in dir, by name.
func pages(t *testing.T, dir string) map[string]string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	for _, e := range entries {
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		out[e.Name()] = string(b)
	}
	return out
}

func sortedNames(m map[string]string) []string {
	var names []string
	for n := range m {
		names = append(names, n)
	}
	slices.Sort(names)
	return names
}

func TestGenerate_OnePagePerCommand(t *testing.T) {
	got := sortedNames(pages(t, runOut(t)))
	// The root, every group and every verb that exists today; none for help or completion.
	want := []string{"abyssctl.md", "abyssctl_host.md", "abyssctl_host_setup.md", "abyssctl_version.md"}
	if !slices.Equal(got, want) {
		t.Errorf("pages = %q, want %q", got, want)
	}
}

func TestGenerate_Deterministic(t *testing.T) {
	first := pages(t, runOut(t))
	runs := []struct {
		name string
		env  []string
	}{
		{"same environment", nil},
		{"other TZ, HOME, LANG and extra variables", []string{
			"TZ=Pacific/Chatham", "HOME=" + t.TempDir(), "LANG=de_DE.UTF-8", "LC_ALL=de_DE.UTF-8",
			"NO_COLOR=1", "COLUMNS=40", "TERM=dumb", "SUDO_USER=operator", "ABYSSCTL_EXTRA=x",
		}},
	}
	for _, r := range runs {
		t.Run(r.name, func(t *testing.T) {
			again := pages(t, runOut(t, r.env...))
			if !slices.Equal(sortedNames(again), sortedNames(first)) {
				t.Fatalf("pages = %q, want %q", sortedNames(again), sortedNames(first))
			}
			for name, body := range first {
				if again[name] != body {
					t.Errorf("%s differs between runs", name)
				}
			}
		})
	}

	date := regexp.MustCompile(`\b(19|20)\d\d-\d\d-\d\d\b|\b\d{1,2}-[A-Z][a-z]{2}-\d{4}\b`)
	for name, body := range first {
		if m := date.FindString(body); m != "" {
			t.Errorf("%s holds a date: %q", name, m)
		}
		if strings.Contains(body, "Auto generated by spf13/cobra") {
			t.Errorf("%s holds Cobra's auto-generated tag", name)
		}
		if strings.Contains(body, buildinfo.Version) {
			t.Errorf("%s holds buildinfo.Version %q", name, buildinfo.Version)
		}
	}
}

var mdLink = regexp.MustCompile(`\]\(([^)]+)\)`)

func TestGenerate_HeaderAndLinks(t *testing.T) {
	got := pages(t, runOut(t))
	const wantHeader = "<!-- Generated by make docs from abyssctl's help text. Do not edit: run make docs. -->\n"
	for name, body := range got {
		if !strings.HasPrefix(body, wantHeader) {
			t.Errorf("%s does not start with the generated-file comment", name)
		}
		for _, m := range mdLink.FindAllStringSubmatch(body, -1) {
			if _, ok := got[m[1]]; !ok {
				t.Errorf("%s links %q, which was not written", name, m[1])
			}
		}
	}
	// The root page is the index: it links every top-level command.
	for _, top := range []string{"abyssctl_host.md", "abyssctl_version.md"} {
		if !strings.Contains(got["abyssctl.md"], "]("+top+")") {
			t.Errorf("abyssctl.md does not link %s", top)
		}
	}
}

func TestGenerate_RemovesStale(t *testing.T) {
	dir := runOut(t)
	for _, name := range []string{"abyssctl_purge.md", "abyssctl_host_teardown.md"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("old\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want := sortedNames(pages(t, runOut(t)))

	if stderr, code := gendocs(t, nil, "-out", dir); code != 0 {
		t.Fatalf("gendocs -out: exit %d\n%s", code, stderr)
	}
	if got := sortedNames(pages(t, dir)); !slices.Equal(got, want) {
		t.Errorf("pages after a second run = %q, want %q", got, want)
	}
}

func TestCheck_ReportsDiffs(t *testing.T) {
	tests := []struct {
		name     string
		change   func(t *testing.T, dir string)
		wantCode int
		wantErr  string
	}{
		{"matching folder", func(*testing.T, string) {}, 0, ""},
		{
			"stale, missing and extra pages",
			func(t *testing.T, dir string) {
				appendTo(t, filepath.Join(dir, "abyssctl_version.md"), "edited by hand\n")
				if err := os.Remove(filepath.Join(dir, "abyssctl_host_setup.md")); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(dir, "abyssctl_purge.md"), []byte("old\n"), 0o644); err != nil {
					t.Fatal(err)
				}
			},
			1,
			"missing abyssctl_host_setup.md\n" +
				"extra abyssctl_purge.md\n" +
				"stale abyssctl_version.md\n" +
				"docs/reference is out of date: run make docs\n",
		},
		{
			"missing folder",
			func(t *testing.T, dir string) {
				if err := os.RemoveAll(dir); err != nil {
					t.Fatal(err)
				}
			},
			1,
			"missing abyssctl.md\n" +
				"missing abyssctl_host.md\n" +
				"missing abyssctl_host_setup.md\n" +
				"missing abyssctl_version.md\n" +
				"docs/reference is out of date: run make docs\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := runOut(t)
			tt.change(t, dir)
			before := snapshot(t, dir)

			stderr, code := gendocs(t, nil, "-check", dir)
			if code != tt.wantCode || stderr != tt.wantErr {
				t.Errorf("gendocs -check = exit %d, stderr\n%s\nwant exit %d, stderr\n%s",
					code, stderr, tt.wantCode, tt.wantErr)
			}
			if after := snapshot(t, dir); !maps.Equal(after, before) {
				t.Errorf("gendocs -check changed the folder:\nbefore %q\nafter  %q", before, after)
			}
		})
	}
}

// secretShaped matches docs.md's Secret shapes: a PEM private key line, or a run of exactly 30 letters and
// digits standing alone (a Pushover user key or token).
var (
	pemKey     = regexp.MustCompile(`-----BEGIN.*PRIVATE KEY-----`)
	pushoverID = regexp.MustCompile(`(^|[^A-Za-z0-9])[A-Za-z0-9]{30}([^A-Za-z0-9]|$)`)
)

// helpProblems lists every way the tree's help text breaks docs.md's help text rules.
func helpProblems(root *cobra.Command) []string {
	var problems []string
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		if !c.IsAvailableCommand() && c != root {
			return
		}
		path := c.CommandPath()
		switch {
		case c.Short == "":
			problems = append(problems, path+": no Short")
		case strings.Contains(c.Short, "\n"):
			problems = append(problems, path+": Short is more than one line")
		case strings.HasSuffix(c.Short, "."):
			problems = append(problems, path+": Short ends with a full stop")
		}
		if c.Runnable() {
			if strings.TrimSpace(c.Long) == "" {
				problems = append(problems, path+": runnable with no Long")
			}
			if strings.TrimSpace(c.Example) == "" {
				problems = append(problems, path+": runnable with no Example")
			}
		}
		// FlagUsages carries each flag's usage and default.
		for _, text := range []string{c.Short, c.Long, c.Example, c.LocalFlags().FlagUsages()} {
			for line := range strings.Lines(text) {
				if pemKey.MatchString(line) || pushoverID.MatchString(line) {
					problems = append(problems, path+": Secret-shaped value in "+strings.TrimSpace(line))
				}
			}
		}
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
	return problems
}

func TestHelp_Complete(t *testing.T) {
	run := func(*cobra.Command, []string) error { return nil }
	tests := []struct {
		name string
		root func() *cobra.Command
		want []string
	}{
		{"abyssctl's tree", cli.Root, nil},
		{"a complete tree", func() *cobra.Command {
			root := &cobra.Command{Use: "x", Short: "Root"}
			root.AddCommand(&cobra.Command{Use: "go", Short: "Go", Long: "Goes.", Example: "  x go", RunE: run})
			return root
		}, nil},
		{"missing and malformed help", func() *cobra.Command {
			root := &cobra.Command{Use: "x"}
			group := &cobra.Command{Use: "grp", Short: "A group."}
			group.AddCommand(&cobra.Command{Use: "go", Short: "Go", RunE: run})
			root.AddCommand(group)
			return root
		}, []string{
			"x: no Short",
			"x grp: Short ends with a full stop",
			"x grp go: runnable with no Long",
			"x grp go: runnable with no Example",
		}},
		{"Secret-shaped values", func() *cobra.Command {
			root := &cobra.Command{Use: "x", Short: "Root"}
			c := &cobra.Command{
				Use: "go", Short: "Go", RunE: run,
				Long:    "Keys look like\n-----BEGIN EC PRIVATE KEY-----\n",
				Example: "  x go --user uQiRzpo4DXghDmr9QzzfQu27cmVRsG\n  x go --ok abcdefghijklmnopqrstuvwxyz01234",
			}
			c.Flags().String("token", "azGDORePK8gMaC0QOYAMyEEuzJnyUi", "the token")
			root.AddCommand(c)
			return root
		}, []string{
			"x go: Secret-shaped value in -----BEGIN EC PRIVATE KEY-----",
			"x go: Secret-shaped value in x go --user uQiRzpo4DXghDmr9QzzfQu27cmVRsG",
			`x go: Secret-shaped value in --token string   the token (default "azGDORePK8gMaC0QOYAMyEEuzJnyUi")`,
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := helpProblems(tt.root()); !slices.Equal(got, tt.want) {
				t.Errorf("problems =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(tt.want, "\n"))
			}
		})
	}
}

func TestRootHelp_CoversContract(t *testing.T) {
	long := cli.Root().Long
	for _, want := range []string{
		"--yes", "--dry-run", "--json", "schema",
		"stdout", "stderr", "NO_COLOR",
		"/var/log/abyssctl/abyssctl.log",
		"terminal",
	} {
		if !strings.Contains(long, want) {
			t.Errorf("the root Long does not name %q", want)
		}
	}
	for code := range 5 {
		row := regexp.MustCompile(`(?m)^\s+` + strconv.Itoa(code) + `\s{2,}\S`)
		if !row.MatchString(long) {
			t.Errorf("the root Long has no row for exit code %d", code)
		}
	}
	// A prompt needs a terminal or --yes: both named in one sentence.
	if !regexp.MustCompile(`terminal[^.]*--yes|--yes[^.]*terminal`).MatchString(long) {
		t.Error("the root Long does not say that a prompt needs a terminal or --yes")
	}
}

func appendTo(t *testing.T, path, text string) {
	t.Helper()
	f, err := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	if _, err := f.WriteString(text); err != nil {
		t.Fatal(err)
	}
}

// snapshot is dir's files with their modification times and contents; a missing folder is empty.
func snapshot(t *testing.T, dir string) map[string]string {
	t.Helper()
	out := map[string]string{}
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return out
	}
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		info, err := e.Info()
		if err != nil {
			t.Fatal(err)
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		out[e.Name()] = info.ModTime().String() + "\n" + string(b)
	}
	return out
}
